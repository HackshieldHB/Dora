/**
 * VENDOR ONLY. Creates the Ed25519 key pair that signs licenses and release integrity manifests.
 *
 *   npm run license:keygen
 *   npm run license:keygen -- --out D:\secure\dora-license-private.pem
 *
 * The private key is written OUTSIDE the project (default: ~/.dora-license/) and must never be
 * copied into the repository, a Docker image or a client's server. Back it up somewhere safe:
 * losing it means no new licenses can be issued for builds that embed its public key.
 * The public key is written into src/lib/license-public-key.ts and compiled into every build.
 */
import { generateKeyPairSync } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";

function option(name: string, fallback: string): string {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? fallback : process.argv[index + 1] || fallback;
}

const out = path.resolve(option("out", path.join(os.homedir(), ".dora-license", "dora-license-private.pem")));
const publicFile = path.resolve(__dirname, "..", "..", "src", "lib", "license-public-key.ts");
const projectRoot = path.resolve(__dirname, "..", "..");

if (out.startsWith(projectRoot + path.sep)) {
  console.error("Refusing to write the private key inside the project folder. Choose a path outside it.");
  process.exit(1);
}
if (existsSync(out)) {
  console.error(`${out} already exists. Refusing to overwrite it: licenses signed with it would stop working.`);
  process.exit(1);
}
const currentPublic = readFileSync(publicFile, "utf8");
if (/BEGIN PUBLIC KEY/.test(currentPublic) && !process.argv.includes("--replace-public")) {
  console.error("src/lib/license-public-key.ts already holds a public key. Pass --replace-public only if you really want to switch keys (existing licenses and builds stay tied to the old key).");
  process.exit(1);
}

const { privateKey, publicKey } = generateKeyPairSync("ed25519");
const privatePem = privateKey.export({ type: "pkcs8", format: "pem" }).toString();
const publicPem = publicKey.export({ type: "spki", format: "pem" }).toString().trim();

mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, privatePem, { mode: 0o600, flag: "wx" });
writeFileSync(
  publicFile,
  `// Generated by \`npm run license:keygen\`. Holds only the PUBLIC half of the vendor signing key.\nexport const LICENSE_PUBLIC_KEY = ${JSON.stringify(publicPem)};\n`,
);

console.log(`Private key: ${out}  (keep secret, back it up offline)`);
console.log(`Public key written to ${path.relative(projectRoot, publicFile)}`);
