export function statusLabel(value?: string | null) {
  const raw = value || "";
  if (!raw) return "—";
  if (LABEL[raw]) return LABEL[raw];
  return raw.split("_").join(" ").toLowerCase().replace(/\b\w/g, (letter) => letter.toUpperCase());
}
