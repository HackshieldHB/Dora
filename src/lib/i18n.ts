export function translate(locale: string, text: string) {
  if (locale !== "id" || !text) return text;
  if (id[text]) return id[text];
  for (const [pattern, build] of GENERATED) {
    const match = text.match(pattern);
    if (match) return build(match);
  }
  return text;
}
